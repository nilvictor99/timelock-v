type MessageKey = keyof typeof messages.es;
const I18nContext = createContext<{ locale: Locale; setLocale: (locale: Locale) => void; t: (key: MessageKey) => string }>({
  locale: "es", setLocale: () => undefined, t: (key) => messages.es[key]
});

export function I18nProvider({ children, initialLocale = "es" }: { children: React.ReactNode; initialLocale?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  useEffect(() => {
    const stored = window.localStorage.getItem("timelock_locale");
    if (stored === "en" || stored === "es") setLocaleState(stored);
  }, []);
  useEffect(() => {
    document.documentElement.lang = locale;
    document.cookie = `timelock_locale=${locale};path=/;max-age=31536000;samesite=lax`;
    window.localStorage.setItem("timelock_locale", locale);
  }, [locale]);
  const value = useMemo(() => ({ locale, setLocale: setLocaleState, t: (key: MessageKey) => messages[locale][key] }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() { return useContext(I18nContext); }
